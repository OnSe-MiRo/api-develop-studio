it('sends explicit server variables only with contract checking and leaves the URL unchanged', async () => {
  const fetch=vi.fn().mockResolvedValue({ok:true,json:async()=>({status:200,body:{ok:true},headers:{},contract:{valid:true,issues:[]}})})
  vi.stubGlobal('fetch',fetch)
  render(<ApiCallPage />)
  await screen.findByRole('option',{name:'sample.json'})
  fireEvent.change(screen.getByLabelText('소유권 확인 프로젝트'),{target:{value:'sample.json'}})
  fireEvent.click(screen.getByLabelText('OpenAPI 실제 응답 검증'))
  fireEvent.change(screen.getByLabelText('OpenAPI server 변수 (JSON)'),{target:{value:'{"version":"v2"}'}})
  fireEvent.change(screen.getByLabelText('Request URL'),{target:{value:'https://example.test/v2/items'}})
  fireEvent.click(screen.getByRole('button',{name:'실행',exact:true}))
  await screen.findByText('응답 계약 검증 통과')
  expect(JSON.parse(fetch.mock.calls[0][1].body)).toMatchObject({serverVariables:{version:'v2'},url:'https://example.test/v2/items',validateContract:true})
  fireEvent.click(screen.getByLabelText('OpenAPI 실제 응답 검증'))
  fireEvent.click(screen.getByRole('button',{name:'실행',exact:true}))
  await screen.findByText('200')
  expect(JSON.parse(fetch.mock.calls[1][1].body)).not.toHaveProperty('serverVariables')
})

